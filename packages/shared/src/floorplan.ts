function buildOuterWalls(polygon: Point2[]): WallSegment[] {
  return polygon.map((point, index) => {
    const next = polygon[(index + 1) % polygon.length]!;
    return {
      id: `outer-${index}`,
      kind: 'outer',
      a: point,
      b: next,
      thickness: 0.22,
      height: 1.35,
    } satisfies WallSegment;
  });
}

